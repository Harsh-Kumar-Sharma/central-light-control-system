#!/usr/bin/env bash
# One-command installer/deployer for Ubuntu.
#   sudo ./deploy.sh                   install prerequisites (if missing) + deploy / update
#   sudo UPDATE_DOCKER=1 ./deploy.sh   also upgrade an already-installed Docker
# Safe to re-run: existing data, secrets and the Admin user are kept.
set -Eeuo pipefail

cd "$(dirname "$(readlink -f "$0")")"
ROOT="$PWD"
COMPOSE_FILE="docker-compose.site.yml"

log()  { printf '\n\033[1;36m==> %s\033[0m\n' "$*"; }
ok()   { printf '\033[1;32m    ok:\033[0m %s\n' "$*"; }
die()  { printf '\n\033[1;31mERROR: %s\033[0m\n' "$*" >&2; exit 1; }
trap 'die "failed at line $LINENO (command: $BASH_COMMAND)"' ERR

# ---- 0. root ---------------------------------------------------------------
if [ "$(id -u)" -ne 0 ]; then
  command -v sudo >/dev/null || die "run as root (sudo not found)"
  exec sudo -E bash "$0" "$@"
fi

# ---- 1. OS check -----------------------------------------------------------
[ -r /etc/os-release ] || die "cannot detect OS"
. /etc/os-release
case "${ID:-}" in ubuntu|debian) ;; *) die "this script supports Ubuntu/Debian only (found: ${ID:-unknown})";; esac
export DEBIAN_FRONTEND=noninteractive

# ---- 2. base packages ------------------------------------------------------
log "Checking base tools (curl, git, openssl, ca-certificates)"
need=()
for p in curl git openssl ca-certificates; do dpkg -s "$p" >/dev/null 2>&1 || need+=("$p"); done
if [ "${#need[@]}" -gt 0 ]; then
  apt-get update -y
  apt-get install -y "${need[@]}"
fi
ok "base tools present"

# ---- 3. Docker -------------------------------------------------------------
log "Checking Docker"
if ! command -v docker >/dev/null 2>&1 || ! docker compose version >/dev/null 2>&1; then
  log "Installing Docker Engine + Compose plugin (official Docker repo)"
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL "https://download.docker.com/linux/${ID}/gpg" -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  CODENAME="${UBUNTU_CODENAME:-${VERSION_CODENAME:-}}"
  [ -n "$CODENAME" ] || die "cannot detect OS codename"
  echo "deb [arch=$(dpkg --print-architecture) signed-by=/etc/apt/keyrings/docker.asc] https://download.docker.com/linux/${ID} ${CODENAME} stable" \
    > /etc/apt/sources.list.d/docker.list
  apt-get update -y
  apt-get install -y docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
elif [ "${UPDATE_DOCKER:-0}" = "1" ]; then
  log "Upgrading Docker packages"
  apt-get update -y
  apt-get install -y --only-upgrade docker-ce docker-ce-cli containerd.io docker-compose-plugin || true
else
  ok "Docker already installed - skipping (set UPDATE_DOCKER=1 to upgrade)"
fi
systemctl enable --now docker >/dev/null 2>&1 || true
for i in $(seq 1 30); do docker info >/dev/null 2>&1 && break; sleep 2; done
docker info >/dev/null 2>&1 || die "Docker daemon is not running"
ok "$(docker --version) / compose $(docker compose version --short)"

# ---- 4. pull latest code (if this is a git clone) --------------------------
if [ -d .git ] && [ "${SKIP_GIT_PULL:-0}" != "1" ]; then
  log "Updating code (git pull)"
  git config --global --add safe.directory "$ROOT" 2>/dev/null || true
  git pull --ff-only || echo "    (git pull skipped/failed - continuing with current code)"
fi

# ---- 5. site config + .env -------------------------------------------------
log "Preparing configuration"
[ -f deploy/site.conf ] || die "deploy/site.conf missing"
# shellcheck disable=SC1091
. deploy/site.conf
: "${SITE_ADMIN_USERNAME:?set SITE_ADMIN_USERNAME in deploy/site.conf}"
: "${SITE_ADMIN_PASSWORD:?set SITE_ADMIN_PASSWORD in deploy/site.conf}"
FRONTEND_PORT="${FRONTEND_PORT:-80}"

# Safety: .env holds the DB password. If it was deleted but the database volume
# still exists, a new random password would not match the existing database.
if [ ! -f .env ] && docker volume ls -q | grep -qx "highway-led-control-site_mysql_data"; then
  die ".env is missing but an existing database was found. Restore the old .env (it holds the DB password). To wipe the old data and start fresh instead, run: sudo docker compose -f ${COMPOSE_FILE} down -v   (this DELETES all data)"
fi

getenv() { if [ -f .env ]; then grep -E "^$1=" .env | head -n1 | cut -d= -f2- || true; fi; }
MYSQL_ROOT_PASSWORD="$(getenv MYSQL_ROOT_PASSWORD)"; [ -n "$MYSQL_ROOT_PASSWORD" ] || MYSQL_ROOT_PASSWORD="$(openssl rand -hex 16)"
JWT_SECRET="$(getenv JWT_SECRET)";                   [ -n "$JWT_SECRET" ]          || JWT_SECRET="$(openssl rand -hex 32)"

# Only characters that are safe inside a .env file / compose interpolation.
case "$SITE_ADMIN_USERNAME$SITE_ADMIN_PASSWORD" in
  *\$*|*\"*|*\'*|*\\*|*\`*|*" "*) die "Admin username/password must not contain \$ \" ' \\ \` or spaces";;
esac

umask 077
cat > .env <<ENVEOF
# Generated by deploy.sh - do not commit. Secrets are kept across re-runs.
MYSQL_ROOT_PASSWORD=${MYSQL_ROOT_PASSWORD}
DB_NAME=highway_led_control
JWT_SECRET=${JWT_SECRET}
SEED_ADMIN_USERNAME=${SITE_ADMIN_USERNAME}
SEED_ADMIN_PASSWORD=${SITE_ADMIN_PASSWORD}
FRONTEND_PORT=${FRONTEND_PORT}
ENVEOF
umask 022
ok ".env written (DB password + JWT secret auto-generated on first run)"

DC=(docker compose -f "$COMPOSE_FILE")

# ---- 6. build + start ------------------------------------------------------
log "Building images (downloads base images/packages on first run - takes a few minutes)"
"${DC[@]}" build

log "Starting database + MQTT broker"
"${DC[@]}" up -d mysql mqtt

log "Running database migrations"
"${DC[@]}" run --rm backend npm run migrate

log "Creating Admin user (first install only)"
"${DC[@]}" run --rm backend npm run seed

log "Starting backend + frontend"
"${DC[@]}" up -d backend frontend

# ---- 6b. firewall: let LAN devices (laptops, phones, transmitters) reach us -
if command -v ufw >/dev/null 2>&1 && ufw status 2>/dev/null | grep -q "Status: active"; then
  log "Firewall (ufw) is active - opening web port ${FRONTEND_PORT} and MQTT 1883"
  ufw allow "${FRONTEND_PORT}/tcp" >/dev/null
  ufw allow 1883/tcp >/dev/null
  ok "ufw rules added"
fi

# ---- 7. verify -------------------------------------------------------------
log "Verifying"
URL="http://127.0.0.1:${FRONTEND_PORT}"
up=0
for i in $(seq 1 40); do
  if curl -fsS "$URL/api/health" 2>/dev/null | grep -q '"ok"'; then up=1; break; fi
  sleep 3
done
if [ "$up" -ne 1 ]; then
  "${DC[@]}" ps || true
  "${DC[@]}" logs --tail=40 backend || true
  die "app did not become healthy"
fi
ok "web + API healthy"

code="$(curl -s -o /dev/null -w '%{http_code}' -X POST "$URL/api/auth/login" \
  -H 'Content-Type: application/json' \
  -d "{\"username\":\"${SITE_ADMIN_USERNAME}\",\"password\":\"${SITE_ADMIN_PASSWORD}\"}" || true)"
if [ "$code" = "200" ]; then ok "Admin login works"
else echo "    note: Admin login returned HTTP $code (expected if the Admin password was changed after first install)"; fi

# ---- 8. summary ------------------------------------------------------------
IP="$(hostname -I 2>/dev/null | awk '{print $1}' || true)"; IP="${IP:-<this-machine-ip>}"
PORT_SUFFIX=""; [ "$FRONTEND_PORT" = "80" ] || PORT_SUFFIX=":${FRONTEND_PORT}"
cat <<DONE

==============================================================
 DEPLOYED.
 Open in a browser:  http://${IP}${PORT_SUFFIX}/
 Admin login:        ${SITE_ADMIN_USERNAME}  (password from deploy/site.conf)
 MQTT broker (for transmitters): ${IP}:1883
 Status:  sudo docker compose -f ${COMPOSE_FILE} ps
 Logs:    sudo docker compose -f ${COMPOSE_FILE} logs -f backend
 Update:  sudo ./deploy.sh        (pulls latest code, data is kept)
==============================================================
DONE
